from __future__ import annotations

from collections.abc import AsyncGenerator

import asyncpg
import pytest

from swiftpy.database.orm.model import Model
from swiftpy.database.pool import DatabasePool
from swiftpy.database.query_builder import Query
from swiftpy.database.transaction import db


class SequenceGapRecord(Model):
    __table__ = "test_sequence_gap_records"
    __fillable__ = ("email",)

    id: int
    email: str


@pytest.fixture
async def sequence_gap_tables(
    ensure_db_pool: DatabasePool | None,
) -> AsyncGenerator[DatabasePool, None]:
    if ensure_db_pool is None:
        pytest.skip("PostgreSQL service is not available in local test environment")

    pool = ensure_db_pool.get_pool()
    async with pool.acquire() as conn:
        await conn.execute(
            """
            DROP TABLE IF EXISTS "test_sequence_gap_records" CASCADE;
            DROP TABLE IF EXISTS "test_identity_gap_records" CASCADE;
            CREATE TABLE "test_sequence_gap_records" (
                id BIGSERIAL PRIMARY KEY,
                email VARCHAR(255) NOT NULL UNIQUE
            );
            CREATE TABLE "test_identity_gap_records" (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                code VARCHAR(64) NOT NULL UNIQUE
            );
            """
        )

    try:
        yield ensure_db_pool
    finally:
        async with pool.acquire() as conn:
            await conn.execute(
                """
                DROP TABLE IF EXISTS "test_sequence_gap_records" CASCADE;
                DROP TABLE IF EXISTS "test_identity_gap_records" CASCADE;
                """
            )


@pytest.mark.asyncio
async def test_postgresql_sequence_skips_ids_after_failed_insert_and_rollback(
    sequence_gap_tables: DatabasePool,
) -> None:
    """
    PostgreSQL sequences backing SERIAL/BIGSERIAL/IDENTITY primary keys are
    non-transactional by design: failed inserts and rolled-back transactions
    consume sequence values cleanly without causing data loss.
    """
    _ = sequence_gap_tables

    # 1. First insert succeeds -> id 1
    first = await SequenceGapRecord.create(email="alice@example.com")
    assert first.id == 1

    # 2. Failed insert (unique violation) still consumes sequence value 2
    with pytest.raises(asyncpg.UniqueViolationError):
        await SequenceGapRecord.create(email="alice@example.com")

    # 3. Rolled-back transaction allocates id 3 then rolls back
    with pytest.raises(RuntimeError, match="force-rollback"):
        async with db.transaction():
            bob = await SequenceGapRecord.create(email="bob@example.com")
            assert bob.id == 3
            raise RuntimeError("force-rollback")

    # 4. Next successful insert receives id 4 (skipping 2 and 3), no rows lost
    carol = await SequenceGapRecord.create(email="carol@example.com")
    assert carol.id == 4

    rows = await Query.table("test_sequence_gap_records").order_by("id", "ASC").get()
    assert rows == [
        {"id": 1, "email": "alice@example.com"},
        {"id": 4, "email": "carol@example.com"},
    ]


@pytest.mark.asyncio
async def test_postgresql_identity_column_skips_id_after_failed_insert_and_rollback(
    sequence_gap_tables: DatabasePool,
) -> None:
    _ = sequence_gap_tables

    row1 = await Query.table("test_identity_gap_records").insert_returning(
        {"code": "ORD-1"}
    )
    assert row1["id"] == 1

    with pytest.raises(asyncpg.UniqueViolationError):
        await Query.table("test_identity_gap_records").insert_returning(
            {"code": "ORD-1"}
        )

    with pytest.raises(RuntimeError, match="rollback-identity"):
        async with db.transaction():
            row_tmp = await Query.table("test_identity_gap_records").insert_returning(
                {"code": "ORD-TMP"}
            )
            assert row_tmp["id"] == 3
            raise RuntimeError("rollback-identity")

    row2 = await Query.table("test_identity_gap_records").insert_returning(
        {"code": "ORD-2"}
    )
    assert row2["id"] == 4

    rows = await Query.table("test_identity_gap_records").order_by("id", "ASC").get()
    assert rows == [
        {"id": 1, "code": "ORD-1"},
        {"id": 4, "code": "ORD-2"},
    ]
